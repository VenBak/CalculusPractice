"""Generate the question bank as JS files for the site.

Usage: python3 -I build.py <output_dir>
"""
import json, os, sys, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import Bank
import foundations as F, derivatives as D, integrals as I, probability as P

AREAS = [
    {'id': 'foundations', 'name': 'Foundations', 'weight': 20, 'lecture': 'L1'},
    {'id': 'derivatives', 'name': 'Derivatives', 'weight': 35, 'lecture': 'L2–L3'},
    {'id': 'integrals', 'name': 'Integrals', 'weight': 22, 'lecture': 'L4–L5'},
    {'id': 'probability', 'name': 'Probability', 'weight': 13, 'lecture': 'L6'},
]

TOPICS = [
    ('domain-range', 'Domain & range', 'foundations', F.domain_range, 'Largest domain of roots, logs and fractions; range of standard functions.'),
    ('inverse', 'Inverse functions', 'foundations', F.inverse, 'Solving y = f(x) for x, domains of inverses and (f⁻¹)′.'),
    ('even-odd', 'Even & odd (parity)', 'foundations', F.even_odd, 'f(−x) = ±f(x), parity of products and compositions.'),
    ('limits', 'Limits', 'foundations', F.limits, 'Simplify, factor, rationalise, squeeze, one-sided limits.'),
    ('asymptotes', 'Asymptotes', 'foundations', F.asymptotes, 'Vertical, horizontal and slant asymptotes.'),
    ('continuity', 'Continuity', 'foundations', F.continuity, 'Piecewise functions, removable discontinuities, differentiability.'),
    ('derivative-rules', 'Differentiation rules', 'derivatives', D.derivative_rules, 'Product, quotient, chain rule and logarithmic differentiation.'),
    ('lhopital', "L'Hôpital & indeterminate forms", 'derivatives', D.lhopital, '0/0, ∞/∞, 0·∞, ∞−∞, 1^∞ and 0^0.'),
    ('implicit-tangent', 'Implicit derivatives & tangent lines', 'derivatives', D.implicit_tangent, 'dy/dx of implicit curves; slope and intercept of tangent lines.'),
    ('partial-derivatives', 'Partial derivatives', 'derivatives', D.partial_derivatives, 'First and mixed partial derivatives, Schwarz.'),
    ('concavity', 'Concavity & inflection points', 'derivatives', D.concavity, "Convex/concave intervals via f'' and inflection points."),
    ('function-analysis', 'Critical points & extrema', 'derivatives', D.function_analysis, 'Critical points, monotonicity, local/absolute extrema, optimisation.'),
    ('substitution', 'Substitution', 'integrals', I.substitution, 'u-substitution, changing bounds, primitives through a point.'),
    ('partial-fractions', 'Partial fractions', 'integrals', I.partial_fractions, 'Decompositions, forms with repeated/quadratic factors.'),
    ('area', 'Area between curves', 'integrals', I.area, 'Areas between graphs and tangent lines, volumes of revolution.'),
    ('riemann', 'Limit of a sum', 'integrals', I.riemann, 'Recognise Riemann sums and evaluate them as integrals.'),
    ('by-parts', 'Integration by parts', 'integrals', I.by_parts, '∫f′g = fg − ∫fg′, repeated parts, combined with substitution.'),
    ('discrete', 'Discrete probability', 'probability', P.discrete, 'Binomial distribution, expectation, variance, counting.'),
    ('continuous', 'Continuous distributions', 'probability', P.continuous, 'pdf normalisation, cdf, expectation, uniform & exponential.'),
    ('conditional', 'Conditional probability & Bayes', 'probability', P.conditional, 'P(A|B), total probability, Bayes’ rule, independence.'),
]


def main(out):
    os.makedirs(os.path.join(out, 'data', 'bank'), exist_ok=True)
    meta = {'areas': AREAS, 'topics': []}
    stats = collections.Counter()
    for i, (tid, name, area, fn, desc) in enumerate(TOPICS):
        B = Bank(tid, 1000 + i)
        fn(B)
        assert len(B.items) >= 25, (tid, len(B.items))
        meta['topics'].append({'id': tid, 'name': name, 'area': area, 'description': desc, 'count': len(B.items)})
        with open(os.path.join(out, 'data', 'bank', tid + '.js'), 'w') as fh:
            fh.write('/* Auto-generated by gen/build.py — %d questions for "%s". */\n' % (len(B.items), name))
            fh.write('window.CalcBank = window.CalcBank || {};\n')
            fh.write('window.CalcBank[%s] = %s;\n' % (json.dumps(tid), json.dumps(B.items, ensure_ascii=False, separators=(',', ':'))))
        stats[tid] = len(B.items)
        pts = collections.Counter(q['points'] for q in B.items)
        print('%-22s %3d questions, %2d MCQ-able, points %s' % (tid, len(B.items), sum('mcq' in q for q in B.items), dict(sorted(pts.items()))))
    with open(os.path.join(out, 'data', 'topics.js'), 'w') as fh:
        fh.write('/* Auto-generated by gen/build.py */\nwindow.CalcTopics = %s;\n' % json.dumps(meta, ensure_ascii=False, indent=1))
    print('total', sum(stats.values()))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
