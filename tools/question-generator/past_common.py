"""Helpers for transcribing real past exams into the site's data format."""
import json
import sympy as sp
from common import (clean, P_num, P_expr, P_int, P_set, P_choice, P_prob, js, L, val, Interval, Union, FiniteSet, oo, S, Q,
                    x, y, t, u)

a, b, n, m = sp.symbols('a b n m', real=True)
FIG = 'assets/past-exams/'


def img(name, alt):
    return '[[img:%s%s|%s]]' % (FIG, name, alt)


def N(label, v, tol=None, pts=None):
    p = P_num(label, sp.sympify(v), tol=tol)
    if pts is not None:
        p['points'] = pts
    return p


def NP(label, v, pts=None):
    p = P_prob(label, sp.sympify(v))
    if pts is not None:
        p['points'] = pts
    return p


def EX(label, e, vars=('x',), sample=None, upc=False, pts=None):
    p = P_expr(label, e, vars=vars, sample=sample, upc=upc)
    if pts is not None:
        p['points'] = pts
    return p


def IV(label, s, loose=False, pts=None):
    p = P_int(label, s)
    if loose:
        p['ignoreClosure'] = True
        p['_shape'] = p['_shape'].split(',')[0] + '. Open or closed endpoints are both accepted here.'
    if pts is not None:
        p['points'] = pts
    return p


def ST(label, vals, pts=None):
    p = P_set(label, vals)
    if pts is not None:
        p['points'] = pts
    return p


def STV(label, exprs, vars, sample, pts=None):
    """A set whose elements contain parameters, e.g. {0, b}."""
    exprs = [sp.sympify(e) for e in exprs]
    p = {'kind': 'set', 'label': label, 'answer': [js(e) for e in exprs], 'vars': list(vars),
         'sample': {k: [float(lo), float(hi)] for k, (lo, hi) in sample.items()},
         'latex': r'\{' + ', '.join(L(e) for e in exprs) + r'\}',
         '_shape': 'There are %d values (they may depend on %s).' % (len(exprs), ', '.join('$%s$' % v for v in vars))}
    if pts is not None:
        p['points'] = pts
    return p


def CH(label, options, correct, pts=None):
    p = P_choice(label, options, correct)
    if pts is not None:
        p['points'] = pts
    return p


def LET(options):
    """Lettered option texts '(A) …' stay as given; the UI adds its own letters, so strip them."""
    return options


def TF(correct_true):
    return P_choice('', ['True', 'False'], 0 if correct_true else 1)


def MULTI(label, options, correct, pts=None):
    p = {'kind': 'multi', 'label': label, 'options': options, 'answer': sorted(correct),
         'latex': ', '.join(options[i] for i in sorted(correct))}
    if pts is not None:
        p['points'] = pts
    return p


def item(label, prompt, parts, points, topic, hint, solution):
    shapes = []
    for p in parts:
        s = p.pop('_shape', None)
        if s and p['kind'] != 'choice':
            shapes.append(((p['label'] + ' ') if len(parts) > 1 and p['label'] else '') + s)
    hints = [hint] + ([' '.join(shapes)] if shapes else [])
    for p in parts:
        if 'points' in p:
            p['points'] = float(p['points'])
    tot = sum(p.get('points', 0) for p in parts)
    if any('points' in p for p in parts):
        assert all('points' in p for p in parts), (label, prompt[:40])
        assert abs(tot - points) < 1e-9, (label, tot, points)
    return {'label': label, 'prompt': prompt, 'parts': parts, 'points': points, 'topic': topic,
            'hints': hints, 'solution': solution}


def question(no, points, intro, items):
    assert abs(sum(i['points'] for i in items) - points) < 1e-9, (no, points, [i['points'] for i in items])
    return {'no': no, 'points': points, 'intro': intro, 'items': items}


def exam(id_, **kw):
    qs = kw['questions']
    total = sum(q['points'] for q in qs)
    assert total == 90, (id_, total)
    d = dict(kw)
    d['id'] = id_
    return clean(d)


def write(exams, out_dir):
    import os
    os.makedirs(out_dir, exist_ok=True)
    index = []
    for e in exams:
        n_items = sum(len(q['items']) for q in e['questions'])
        index.append({k: e[k] for k in ('id', 'year', 'sitting', 'kind', 'date', 'iso', 'minutes', 'file', 'note') if k in e} |
                     {'questions': len(e['questions']), 'items': n_items})
        with open(os.path.join(out_dir, e['id'] + '.js'), 'w') as fh:
            fh.write('/* Past exam %s (%s) — transcribed from %s.pdf with the official answers. Generated by tools/question-generator/past_exams.py */\n' % (e['id'], e['date'], e['file']))
            fh.write('window.CalcPast = window.CalcPast || {};\n')
            fh.write('window.CalcPast[%s] = %s;\n' % (json.dumps(e['id']), json.dumps(e, ensure_ascii=False, separators=(',', ':'))))
    with open(os.path.join(out_dir, 'index.js'), 'w') as fh:
        fh.write('/* Past exams available on the site. Generated by tools/question-generator/past_exams.py */\n')
        fh.write('window.CalcPastIndex = %s;\n' % json.dumps(index, ensure_ascii=False, indent=1))
    return index
